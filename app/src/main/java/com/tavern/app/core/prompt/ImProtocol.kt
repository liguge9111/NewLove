package com.tavern.app.core.prompt

/**
 * IM 聊天协议说明
 *
 * 互动模式下注入：告知模型玩家可能通过手机发消息，
 * 并说明 [IM] 块的输出格式。是否回复由模型根据剧情自由决定。
 */
object ImProtocol {

    val INSTRUCTION = """
        【手机消息】
        玩家可能会通过手机聊天软件给角色发消息，这类消息会在叙事中以「发去手机消息」的形式呈现。
        如果角色会在聊天软件中回复（是否回复、何时回复由你根据剧情和角色性格自由决定），请在回复正文的最后额外输出聊天回复内容，格式：
        [IM]
        角色的聊天回复（口语化、简短，符合聊天软件语气）
        [/IM]
        [IM] 块只包含角色在聊天界面里发出的文字，不要包含动作描写或叙事；若本回合无需聊天回复，则不要输出该块。
    """.trimIndent()
}
